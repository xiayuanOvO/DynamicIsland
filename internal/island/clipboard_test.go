func TestClipboardLoadsOnePageAtATimeWhileScrolling(t *testing.T) {
	texts := make([]string, 2*clipboardPageSize)
	for i := range texts {
		texts[i] = fmt.Sprintf("记录 %02d", i)
	}
	a := newTestClipboard(t, true, texts...)
	a.openClipboard(true)
	view := ui.NewTester(func(c *ui.Context) { a.clipboardView(c, true, nil) }, panelWidth, clipboardPanelHeight)
	first := a.clipboard.selected
	view.Scroll(20, 125, 0, 106)
	if len(a.clipboard.entries) != clipboardPageSize {
		t.Fatal("scrolling near the start should leave only the first page loaded")
	}
	view.Scroll(20, 125, 0, 3000)
	if len(a.clipboard.entries) != len(texts) || a.clipboard.hasMore || a.clipboard.selected != first {
		t.Fatal("scrolling to the end should append exactly one page and keep the selection")
	}
	if !view.HasText(texts[clipboardPageSize-1]) || view.HasText(texts[len(texts)-1]) {
		t.Fatal("appending a page should keep the viewport near the page boundary")
	}
	view.Scroll(20, 125, 0, 3000)
	if !view.HasText(texts[len(texts)-1]) || len(a.clipboard.entries) != len(texts) {
		t.Fatal("continuing to scroll should reach the oldest entry without loading more pages")
	}
	a.clipboard.open = false
	a.openClipboard(true)
	view.Frame()
	if len(a.clipboard.entries) != clipboardPageSize || !view.HasText(texts[0]) {
		t.Fatal("reopening history should start again at the first page")
	}
}

func TestClipboardKeyboardContinuesAcrossSearchPages(t *testing.T) {
	texts := make([]string, 0, 2*clipboardPageSize+2)
	for i := range clipboardPageSize + 1 {
		texts = append(texts, fmt.Sprintf("无关 %02d", i), fmt.Sprintf("文本 %02d\n匹配", i))
	}
	a := newTestClipboard(t, true, texts...)
	a.openClipboard(true)
	var copied string
	view := ui.NewTester(func(c *ui.Context) {
		if a.clipboard.open {
			a.clipboardView(c, true, func(data transfer.Data) error {
				value, err := data.Read(transfer.Text)
				copied = string(value)
				return err
			})
		}
		a.shortcuts(c)
	}, panelWidth, clipboardPanelHeight)
	view.Type("匹配")
	if len(a.clipboard.entries) != clipboardPageSize || a.clipboard.entries[clipboardPageSize-1].Preview != "文本 49…" || !a.clipboard.hasMore {
		t.Fatal("search should find a full page of matching text across the entire history")
	}
	for range clipboardPageSize - 2 {
		view.Key(0, ui.KeyDown)
	}
	if len(a.clipboard.entries) != clipboardPageSize {
		t.Fatal("arrow navigation should not load more until the selection reaches the last row")
	}
	view.Key(0, ui.KeyDown)
	if len(a.clipboard.entries) != clipboardPageSize+1 || a.clipboard.hasMore || a.clipboard.selected != a.clipboard.entries[clipboardPageSize-1].ID {
		t.Fatal("reaching the last row should load more results without skipping that row")
	}
	view.Key(0, ui.KeyDown)
	if a.clipboard.selected != a.clipboard.entries[clipboardPageSize].ID || !view.HasText("文本 50…") || !view.Focused("搜索剪贴板历史") {
		t.Fatal("Down should select and reveal the first row of the next page while keeping search focused")
	}
	view.Key(0, ui.KeyEnter)
	if copied != "文本 50\n匹配" || a.clipboard.open {
		t.Fatal("Enter should copy the selected record from the next page and close the panel")
	}
}

func TestClipboardDistinguishesScrollFromPointerMovement(t *testing.T) {
	texts := make([]string, 12)
	for i := range texts {
		texts[i] = fmt.Sprintf("记录 %02d", i)
	}
	a := newTestClipboard(t, true, texts...)
	a.openClipboard(true)
	view := ui.NewTester(func(c *ui.Context) { a.clipboardView(c, true, nil) }, panelWidth, clipboardPanelHeight)
	first := a.clipboard.entries[0].ID
	view.Scroll(20, 125, 0, 106)
	if a.clipboard.selected != first {
		t.Fatal("a scroll event must not select the row at its pointer position")
	}
	view.Wheel(21, 125, 0, 53)
	view.Advance(70 * time.Millisecond)
	if a.clipboard.selected != first {
		t.Fatal("wheel scrolling alone must keep the current selection")
	}
	next, found := view.Find("复制 记录 04")
	if !found {
		t.Fatal("the target row should be visible during scrolling")
	}
	view.Move(next.X+20, next.Y+next.H/2)
	selected := a.clipboard.entries[4].ID
	if a.clipboard.selected != selected {
		t.Fatal("a real mouse move should select the row immediately during scrolling")
	}
	view.Advance(140 * time.Millisecond)
	if a.clipboard.selected != selected {
		t.Fatal("rows scrolling under a stationary mouse must not change the selection")
	}
}

func TestClipboardPinMovesToTopAndSurvivesExpiry(t *testing.T) {
	a := newTestClipboard(t, true, "最新记录", "常用邮箱", "较早记录")
	a.openClipboard(false)
	view := ui.NewTester(func(c *ui.Context) { a.clipboardView(c, true, nil) }, panelWidth, clipboardPanelHeight)

	if err := view.Click("置顶记录 常用邮箱"); err != nil {
		t.Fatal(err)
	}
	if len(a.clipboard.entries) != 3 || a.clipboard.entries[0].Preview != "常用邮箱" || !a.clipboard.entries[0].Pinned {
		t.Fatalf("pinning should move the entry to the top: %+v", a.clipboard.entries)
	}

	// Verify pagination across pinned and unpinned entries.
	page1, more, err := a.clipboard.store.entryPage("", time.Now(), clipboardEntry{}, 2)
	if err != nil || !more || len(page1) != 2 || page1[0].Preview != "常用邮箱" || page1[1].Preview != "最新记录" {
		t.Fatalf("first page should return pinned then newest unpinned: %+v, more=%v, err=%v", page1, more, err)
	}
	page2, more, err := a.clipboard.store.entryPage("", time.Now(), page1[1], 2)
	if err != nil || more || len(page2) != 1 || page2[0].Preview != "较早记录" {
		t.Fatalf("second page should return remaining unpinned entry: %+v, more=%v, err=%v", page2, more, err)
	}

	// Verify pinned entry survives 90-day expiry while unpinned entries expire.
	future := time.Now().Add(clipboardRetention + time.Hour)
	changed, err := a.clipboard.store.expire(future)
	if err != nil || !changed {
		t.Fatalf("unpinned entries should expire after retention: changed=%v, err=%v", changed, err)
	}
	remaining := readTestClipboardEntries(t, a.clipboard.store, future)
	if len(remaining) != 1 || remaining[0].Preview != "常用邮箱" || !remaining[0].Pinned {
		t.Fatalf("pinned entry should survive expiry: %+v", remaining)
	}

	// Unpinning should restore normal state and allow expiry.
	if err := view.Click("取消置顶记录 常用邮箱"); err != nil {
		t.Fatal(err)
	}
	if len(a.clipboard.entries) != 1 || a.clipboard.entries[0].Pinned {
		t.Fatalf("unpinning should clear the pinned flag: %+v", a.clipboard.entries)
	}
	changed, err = a.clipboard.store.expire(future)
	if err != nil || !changed {
		t.Fatalf("unpinned entry should expire after retention: changed=%v, err=%v", changed, err)
	}
	if remaining := readTestClipboardEntries(t, a.clipboard.store, future); len(remaining) != 0 {
		t.Fatalf("unpinned expired entry should be removed: %+v", remaining)
	}
}
