func TestClipboardHistoryPersistsRecentText(t *testing.T) {
	a := island{statePath: filepath.Join(t.TempDir(), "shelf.json")}
	a.loadClipboard()
	now := time.Now()
	if a.recordClipboard("样本文字", now) {
		t.Fatal("clipboard recording must start disabled")
	}
	if !a.saveClipboard(clipboardState{Recording: true}) {
		t.Fatal(a.clipboard.problem)
	}
	for i := range clipboardHistoryLimit + 1 {
		if !a.recordClipboard(fmt.Sprintf("样本文字 %d", i), now) {
			t.Fatalf("did not record sample %d", i)
		}
	}
	if got := a.clipboard.Entries; len(got) != clipboardHistoryLimit || got[len(got)-1].Text != "样本文字 1" {
		t.Fatal("history did not evict the oldest sample")
	}
	const multiline = " 中文 😀\n保留空白  "
	later := now.Add(time.Minute)
	a.recordClipboard(multiline, now)
	a.recordClipboard("样本文字 2", now)
	a.recordClipboard(multiline, later)
	if a.clipboard.Entries[0].Text != multiline || !a.clipboard.Entries[0].CopiedAt.Equal(later) ||
		slices.ContainsFunc(a.clipboard.Entries[1:], func(entry clipboardEntry) bool { return entry.Text == multiline }) {
		t.Fatal("a repeated copy should put the exact text first without duplicating it")
	}
	for _, ignored := range []string{"", " \n", "bad\x00text", strings.Repeat("x", clipboardTextLimit+1), multiline} {
		if a.recordClipboard(ignored, now) {
			t.Fatal("invalid or already-recent text changed the history")
		}
	}
	state := a.clipboard.clipboardState
	state.Recording = false
	if !a.saveClipboard(state) {
		t.Fatal(a.clipboard.problem)
	}
	reopened := island{statePath: a.statePath}
	reopened.loadClipboard()
	if reopened.clipboard.Recording || !slices.EqualFunc(reopened.clipboard.Entries, state.Entries, func(a, b clipboardEntry) bool {
		return a.Text == b.Text && a.CopiedAt.Equal(b.CopiedAt)
	}) {
		t.Fatal("reopening did not restore paused recording and saved entries")
	}
}

func TestClipboardTextHonorsClipboardHistoryMarkers(t *testing.T) {
	for _, format := range []transfer.Format{"org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
		"org.nspasteboard.AutoGeneratedType", "ExcludeClipboardContentFromMonitorProcessing", "x-kde-passwordManagerHint", transfer.PNG} {
		formats := []transfer.Format{format}
		if format != transfer.PNG {
			formats = append(formats, transfer.Text)
		}
		if text := readClipboardText(formats, func(...transfer.Format) (transfer.Data, error) {
			t.Fatalf("requested data for skipped format %s", format)
			return transfer.Data{}, nil
		}); text != "" {
			t.Fatalf("saved text for skipped format %s", format)
		}
	}
	for _, flag := range []byte{0, 1} {
		formats := []transfer.Format{transfer.Text, clipboardHistoryFlag}
		text := readClipboardText(formats, func(requested ...transfer.Format) (transfer.Data, error) {
			if !slices.Equal(formats, requested) {
				t.Fatalf("unexpected formats %v", requested)
			}
			return transfer.New(transfer.NewItem(transfer.Bytes(transfer.Text, []byte("示例")),
				transfer.Bytes(clipboardHistoryFlag, []byte{flag, 0, 0, 0}))), nil
		})
		if (text == "示例") != (flag == 1) {
			t.Fatalf("unexpected history text for flag %d", flag)
		}
	}
}

func TestClipboardPanelDeletesAndClearsSavedHistory(t *testing.T) {
	a := island{expanded: true, files: &shelf.Shelf{}, statePath: filepath.Join(t.TempDir(), "shelf.json")}
	if !a.saveClipboard(clipboardState{Recording: true, Entries: []clipboardEntry{
		{Text: "样本文字 1", CopiedAt: time.Now()},
		{Text: "样本文字 2", CopiedAt: time.Now()},
	}}) {
		t.Fatal(a.clipboard.problem)
	}
	view := ui.NewTester(func(c *ui.Context) {
		a.body(c, a.targetFrame())
		a.shortcuts(c)
	}, panelWidth, clipboardPanelHeight+20)
	card, ok := view.Find("查看剪贴板历史")
	todo, todoOK := view.Find("待办卡片")
	if !ok || !todoOK || card.X < todo.X+todo.W {
		t.Fatalf("overview cards overlap or are missing: clipboard %+v, todo %+v", card, todo)
	}
	view.Key(0, ui.KeyTab)
	view.Key(0, ui.KeyTab)
	if !view.Focused("查看剪贴板历史") {
		t.Fatal("Tab did not reach the clipboard card")
	}
	view.Key(0, ui.KeyEnter)
	if !a.clipboard.open {
		t.Fatal("Enter did not open the focused clipboard card")
	}
	for _, action := range []string{"删除记录 样本文字 1", "清空历史"} {
		if err := view.Click(action); err != nil {
			t.Fatal(err)
		}
	}
	if len(a.clipboard.Entries) != 1 || !a.clipboard.confirmClear {
		t.Fatal("deleting should remove one entry and clearing should ask for confirmation")
	}
	view.Key(0, ui.KeyEscape)
	if !a.clipboard.open || a.clipboard.confirmClear {
		t.Fatal("Escape should cancel confirmation while keeping the panel open")
	}
	for range 2 {
		if err := view.Click("清空历史"); err != nil {
			t.Fatal(err)
		}
	}
	if len(a.clipboard.Entries) != 0 || a.clipboard.confirmClear {
		t.Fatal("confirmation should clear the list")
	}
	reopened := island{statePath: a.statePath}
	reopened.loadClipboard()
	if len(reopened.clipboard.Entries) != 0 || reopened.clipboard.loadFailed {
		t.Fatal("the empty list was not saved")
	}
	view.Key(0, ui.KeyEscape)
	if a.clipboard.open || !a.expanded {
		t.Fatal("Escape should return to the expanded overview")
	}
}

func TestClipboardHistorySaveFailureLeavesEntriesIntact(t *testing.T) {
	a := island{statePath: filepath.Join(t.TempDir(), "shelf.json")}
	state := clipboardState{Entries: []clipboardEntry{{Text: "示例", CopiedAt: time.Now()}}}
	if !a.saveClipboard(state) {
		t.Fatal(a.clipboard.problem)
	}
	if err := os.Mkdir(a.clipboardPath()+".tmp", 0700); err != nil {
		t.Fatal(err)
	}
	if a.saveClipboard(clipboardState{}) || !slices.Equal(a.clipboard.Entries, state.Entries) || a.clipboard.problem == "" {
		t.Fatal("a failed save changed history or did not report the error")
	}
}
